// Operadores de atribuição (Assignment)
let x

// Assignment
x = 1

// addition Assignment
// x = x + 2
x += 2

// subtraction Assignment
// x = x - 1
x -= 1

// multiplication Assignment
// x = x * 2
x *= 2

// division Assignment
// x = x / 2
x /= 2

// remainder, exponetiation
x %= 2
x **= 2

console.log(x)